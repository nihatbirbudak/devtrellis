  const TR = {};
  function register(messages = {}) {
    if (messages.en && typeof messages.en === "object") Object.assign(EN, messages.en);
    if (messages.tr && typeof messages.tr === "object") Object.assign(TR, messages.tr);
  }
  function createTranslator(language = "en") {
    return (key, values = {}) => {
      const template = (language === "en" ? EN[key] : TR[key]) || key;
      return String(template).replace(/UFUK|Ufuk/g, BRAND).replace(/\{(\w+)\}/g, (match, name) => Object.hasOwn(values, name) ? String(values[name]) : match);
    };
  }
  async function loadTopicLabels(language, fetcher) {
    const labels = Object.create(null);
    try {
      const response = await fetcher("/api/topics", {credentials: "same-origin", headers: {Accept: "application/json"}});
      if (!response.ok) return labels;
      const definitions = await response.json();
      if (!Array.isArray(definitions)) return labels;
      const field = language === "en" ? "label_en" : "label_tr";
      for (const topic of definitions) {
        if (topic && typeof topic.id === "string" && typeof topic[field] === "string" && topic[field].trim()) labels[topic.id] = topic[field];
      }
    } catch { /* Konu listesi alınamasa da kayıtlar mevcut etiketleriyle okunabilir. */ }
    return labels;
  }
  function provenanceFacts(value, translate, dateLabel) {
    if (!value || typeof value !== "object") return [];
    const evidence = {verified: "Kaynak eşleşmesi kaydedilmiş", unverified: "Denetlenmemiş", insufficient: "Yetersiz dayanak", unknown: "Bilinmiyor"};
    const facts = [[translate("Kaynak araştırmanın modeli"), !value.model || value.model === "unknown" ? translate("Model kaydedilmemiş") : value.model],
      [translate("Araştırmanın üretim tarihi"), value.generated_at ? dateLabel(value.generated_at) : translate("Üretim tarihi kaydedilmemiş")],
      [translate("Araştırma sorusu"), value.question || translate("Belirtilmedi")],
      [translate("Kartın kanıt durumu"), translate(evidence[value.modified ? "unverified" : value.evidence_status] || "Bilinmiyor")]];
    if (typeof value.claim_text === "string" && value.claim_text.trim()) facts.push([translate("İncelenen iddia"), value.claim_text]);
    return facts;
  }

